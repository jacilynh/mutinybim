import assert from "node:assert/strict";
import { test } from "node:test";
import { register } from "tsx/esm/api";

register();
const { renderCloseout } = await import("./closeout.tsx");
const { createSurveyWorkflow, readSurvey } = await import("./workflow.mjs");

test("review the two MH1 shots and record the outlet invert only after preview", async () => {
  const workflow = await createSurveyWorkflow();
  const design = await workflow.designModel();
  const originalRecord = await workflow.recordModel();
  assert.throws(() => readSurvey(workflow.csv.replace(",DEMO-BM1,", ",OTHER,"), design), /datum/);
  assert.throws(() => readSurvey(workflow.csv.replace(",out,", ",in_e,"), design), /pipe and connector/);
  assert.throws(() => readSurvey(workflow.csv.replace(",m,", ",ft,"), design), /metres/);
  assert.throws(() => readSurvey(workflow.csv.replace("MH1-02", "MH1-01"), design), /occur once/);
  assert.throws(() => readSurvey(workflow.csv.replace("P103-s1,MH1,out", "P101-s1,MH1,in_e"), design), /occur once/);
  await workflow.act("import");
  assert.deepEqual((await workflow.state()).observations.map(({ deltaMm }) => deltaMm), [0, 40]);
  await assert.rejects(workflow.act("accept", "unreviewed"), /Preview/);
  await workflow.act("preview");
  assert.deepEqual(await workflow.recordModel(), originalRecord);
  assert.equal(renderCloseout(await workflow.state(), "/mh1-survey.csv"), null);
  const firstPreview = (await workflow.state()).preview;
  await workflow.act("import");
  assert.equal((await workflow.state()).preview, null);
  await assert.rejects(workflow.act("accept", firstPreview.id), /Preview/);
  await workflow.act("preview");
  const supersededPreview = (await workflow.state()).preview;
  await workflow.act("preview");
  const { preview } = await workflow.state();
  await assert.rejects(workflow.act("accept", supersededPreview.id), /Preview/);
  assert.deepEqual(await workflow.recordModel(), originalRecord);
  await workflow.act("accept", preview.id);
  const accepted = await workflow.state();
  assert.equal(accepted.recordRevision, originalRecord.revision + 1);
  assert.equal(accepted.recordEntry, "28996 mm · DEMO-BM1 · P103-s1/MH1/out · mh1-survey.csv#MH1-02");
  const html = renderCloseout(accepted, "/mh1-survey.csv");
  assert.ok(html.includes(accepted.recordEntry));
  assert.match(html, /Design revision 24 · Record revision 25/);
  assert.match(html, /MH1-01/);
  assert.match(html, /\+40 mm/);
  assert.match(html, /<svg/);
  await workflow.act("accept", preview.id);
  await assert.rejects(workflow.act("accept", supersededPreview.id), /already been recorded/);
  assert.deepEqual(await workflow.state(), accepted);
  assert.deepEqual(await workflow.designModel(), design);
  assert.deepEqual((await workflow.recordModel()).elements["P103-s1"], originalRecord.elements["P103-s1"]);
});
